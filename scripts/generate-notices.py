#!/usr/bin/env python3
"""Collect dependency license notices from the versions in Cargo.lock."""
import argparse
import json
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
options = parser.parse_args()
root = Path(__file__).resolve().parent.parent
metadata = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--locked", "--format-version", "1"], cwd=root, text=True))
packages = sorted((p for p in metadata["packages"] if p["source"]),
                  key=lambda p: (p["name"], p["version"]))
notices = {}
lines = [
    "Dotheap third-party notices",
    "==========================",
    "",
    "Generated by scripts/generate-notices.py from Cargo.lock.",
    "Includes Cargo dependencies, runtime notices, and upstream source acknowledgments.",
    "License expressions below retain the alternatives offered by each project.",
    "Dependency sources are available at the versioned crates.io links below.",
    "These licenses apply to the named dependencies, not to Dotheap's own source code.",
    "",
]
for package in packages:
    name, version = package["name"], package["version"]
    lines.extend([
        f"{name} {version} — {package['license'] or 'see license file'}",
        f"  Source: https://crates.io/crates/{name}/{version}",
    ])
    directory = Path(package["manifest_path"]).parent
    files = sorted(p for p in directory.rglob("*") if p.is_file()
                   and p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE")))
    if name == "r-efi":
        files.append(directory / "AUTHORS")
    if not files:
        raise SystemExit(f"No license notice found for {name} {version}")
    for path in files:
        text = "\n".join(line.rstrip() for line in path.read_text().strip().splitlines())
        label = path.relative_to(directory) if path.is_relative_to(directory) else path.name
        notices.setdefault(text, []).append(f"{name} {version}: {label}")
lines.extend(["", "License texts and notices", "========================", ""])
for text, owners in notices.items():
    lines.extend(["\n".join(owners), "-" * 72, text, ""])
lines.extend(["Runtime components and source references", "=======================================", ""])
for path in sorted((root / "third-party").glob("*.txt")):
    lines.extend([path.read_text().strip(), ""])
content = "\n".join(lines)
output = root / "THIRD-PARTY-NOTICES.txt"
if options.check:
    if not output.is_file() or output.read_text() != content:
        raise SystemExit("Dependency notices changed; run python3 scripts/generate-notices.py")
else:
    output.write_text(content)
