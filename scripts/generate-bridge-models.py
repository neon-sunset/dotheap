"""Generate immutable Swift projections and a C ABI from the Rust bridge API."""

from pathlib import Path
import re
import subprocess
import textwrap

ROOT = Path(__file__).resolve().parents[1]
SELECTED = """
AnalysisOptions TypeStats RegionStats OccupancyHistogram MemoryPart HeapKind Page Region
MethodTableInfo RootSource GcHandle NativeMemory Category MallocParameters
Residency SmapsMapping Versions Platform FileMapping Thread TypeGroup HandleGroup
Word FieldValue StructElement ReferenceElement TextPreview DominatorGroup Granule RegionStrip
Chunk ChunkGroup ReachTotal OwnershipGroup OwnershipNode CheckReport SummaryFinding TaskGraphs
ThreadInfo ThreadState ThreadGroup StackNode DuplicateString CollectionCapacity ZeroArrays
TypeCount Finalizable GarbageGroup Timers Network Files FragmentationReport SearchResult
SymbolDownload Process CacheEntry QueuedWorkItem AsyncAnalysis HeapVerification
""".split()
OBJECTS = ['Snapshot', 'NativeGraphView', 'OwnershipView', 'GarbageView', 'ThreadStacksView']
PRIMITIVES = {
    'u8': ('uint8_t', 'UInt8'), 'u16': ('uint16_t', 'UInt16'),
    'u32': ('uint32_t', 'UInt32'), 'u64': ('uint64_t', 'UInt64'),
    'i32': ('int32_t', 'Int32'), 'i64': ('int64_t', 'Int64'),
    'usize': ('uintptr_t', 'Int'), 'bool': ('bool', 'Bool'), 'f64': ('double', 'Double'),
}


def split(text):
    depth, start = 0, 0
    result = []
    for i, char in enumerate(text):
        if char in '<([{':
            depth += 1
        if char in '>)]}':
            depth -= 1
        if char == ',' and depth == 0:
            if text[start:i].strip():
                result.append(text[start:i].strip())
            start = i + 1
    if text[start:].strip():
        result.append(text[start:].strip())
    return result


def clean(ty):
    return re.sub(r'\bIndex\b', 'usize', ty.strip())


def inner(ty, outer):
    return ty[len(outer) + 1:-1] if ty.startswith(outer + '<') else None


def camel(name):
    parts = name.removeprefix('r#').split('_')
    return parts[0][:1].lower() + parts[0][1:] + ''.join(p.title() for p in parts[1:])


def swift_name(name):
    name = camel(name)
    reserved = {
        'associatedtype', 'class', 'deinit', 'enum', 'extension', 'fileprivate', 'func',
        'import', 'init', 'inout', 'internal', 'let', 'open', 'operator', 'private',
        'protocol', 'public', 'rethrows', 'static', 'struct', 'subscript', 'typealias',
        'var', 'break', 'case', 'catch', 'continue', 'default', 'defer', 'do', 'else',
        'fallthrough', 'for', 'guard', 'if', 'in', 'repeat', 'return', 'switch', 'throw',
        'where', 'while', 'as', 'false', 'is', 'nil', 'self', 'Self', 'super', 'throws',
        'true', 'try', 'async', 'await', 'some', 'any',
    }
    return '`' + name + '`' if name in reserved else name


def key(ty):
    return re.sub(r'\W+', '_', ty).strip('_')


def load_primitive(ty, pointer):
    if ty == 'usize':
        return f'Int({pointer}.load(as: UInt.self))'
    return f'{pointer}.load(as: {PRIMITIVES[ty][1]}.self)'


def definitions():
    found = {}
    for path in sorted((ROOT / 'crates/heap-core/src').glob('*.rs')):
        source = path.read_text()
        for match in re.finditer(r'^pub (struct|enum) (\w+) \{', source, re.M):
            end = source.index('\n}', match.end())
            body = source[match.end():end]
            body = re.sub(r'^\s*#\[[^\n]*\]\n', '', body, flags=re.M)
            body = re.sub(r'//[^\n]*', '', body)
            found[match[2]] = (f'heap_core::{path.stem}', match[1], body)
    chosen = {}

    def include(name):
        if name in chosen:
            return
        chosen[name] = found[name]
        body = found[name][2]
        if found[name][1] == 'enum':
            body = re.sub(r'^    [A-Z]\w*', '', body, flags=re.M)
        for word in re.findall(r'\b[A-Z]\w*\b', body):
            if word in found:
                include(word)

    for name in SELECTED:
        include(name)
    for module in ['snapshot', 'objects', 'graphs']:
        source = (ROOT / f'crates/heap-bridge/src/{module}.rs').read_text()
        for match in re.finditer(r'^pub struct (\w+) \{', source, re.M):
            if match[1] in OBJECTS:
                continue
            end = source.index('\n}', match.end())
            chosen[match[1]] = (f'crate::{module}', 'struct', source[match.end():end])
    return chosen


class Generator:
    def __init__(self):
        self.models = definitions()
        self.readers = set()
        self.rust = [
            '// Generated by scripts/generate-bridge-models.py.',
            '#![allow(non_snake_case, unused_imports, unused_unsafe)]',
            'use crate::{ffi::{self, Owned, Outcome, Slice}, models::*, snapshot::*, graphs::*, objects::*};',
            'use std::{ffi::c_void, sync::Arc, path::PathBuf, collections::{BTreeMap, BTreeSet, HashMap}};',
        ]
        self.header = [
            '// Generated by scripts/generate-bridge-models.py.', '#pragma once',
            '#include <stdint.h>', '#include <stdbool.h>',
            'typedef struct { const void *data; uintptr_t len; uintptr_t stride; } DHSlice;',
            'typedef struct { const void *data; void (*destroy)(const void *); } DHOwned;',
            'typedef struct { DHOwned value; DHOwned error; } DHOutcome;',
            'typedef struct { bool present; DHSlice value; } DHOptionalString;',
            'typedef struct { void *context; void (*update)(void *, DHSlice, double); bool (*cancelled)(void *); void (*destroy)(void *); } DHProgress;',
        ]
        self.swift = ['// Generated by scripts/generate-bridge-models.py.', 'import RustHeapCoreFFI', 'import Foundation']

    def export(self, name, args, ret, body):
        rust_args = ', '.join(n + ': ' + r for n, r, c in args)
        c_args = ', '.join(c + ' ' + n for n, r, c in args) or 'void'
        self.rust.append(f'#[unsafe(no_mangle)]\npub unsafe extern "C" fn {name}({rust_args}) -> {ret[0]} {{\nunsafe {{ {body} }}\n}}')
        self.header.append(f'{ret[1]} {name}({c_args});')

    def swift_type(self, ty):
        ty = clean(ty)
        if ty.startswith('&['):
            return 'RustArray<' + self.swift_type(ty[2:-1]) + '>'
        if ty.startswith('&'):
            return self.swift_type(ty[1:])
        if ty in PRIMITIVES:
            return PRIMITIVES[ty][1]
        if ty in ('String', 'str', 'PathBuf'):
            return 'String'
        if ty == '()':
            return 'Void'
        if (t := inner(ty, 'Option')) is not None:
            return self.swift_type(t) + '?'
        if (t := inner(ty, 'Vec')) is not None:
            return 'RustArray<' + self.swift_type(t) + '>'
        if (t := inner(ty, 'Arc')) is not None:
            return self.swift_type(t)
        if ty.startswith('['):
            return 'RustArray<' + self.swift_type(ty[1:ty.index(';')]) + '>'
        if (t := inner(ty, 'BTreeSet')) is not None:
            return '[' + self.swift_type(t) + ']'
        for name in ['BTreeMap', 'HashMap']:
            if (t := inner(ty, name)) is not None:
                a, b = split(t)
                if a in PRIMITIVES and b in PRIMITIVES:
                    return 'RustMap<' + self.swift_type(a) + ', ' + self.swift_type(b) + '>'
                return '[' + self.swift_type(a) + ': ' + self.swift_type(b) + ']'
        return ty

    def reader(self, ty):
        ty = clean(ty).removeprefix('&')
        if ty in OBJECTS:
            return f'{{ _, owner in {ty}(owner: owner) }}'
        name = 'read_' + key(ty)
        if ty in self.readers:
            return name
        self.readers.add(ty)
        f = 'dh_read_' + key(ty)
        arg = [('pointer', '*const c_void', 'const void *')]
        ptr = f'&*pointer.cast::<{ty}>()'
        value = 'pointer.load(as: ' + self.swift_type(ty) + '.self)'
        if ty in PRIMITIVES:
            value = load_primitive(ty, 'pointer')
        elif ty == '()':
            value = '()'
        elif ty in ('String', 'PathBuf'):
            bytes_expr = f'({ptr}).as_bytes()' if ty == 'String' else f'({ptr}).as_os_str().as_encoded_bytes()'
            self.export(f, arg, ('Slice', 'DHSlice'), f'Slice::new({bytes_expr})')
            value = f'readString({f}(pointer))'
        elif (t := inner(ty, 'Option')) is not None:
            self.export(f, arg, ('*const c_void', 'const void *'), f'({ptr}).as_ref().map_or(std::ptr::null(), |v| (v as *const {t}).cast())')
            value = f'{f}(pointer).map {{ {self.reader(t)}($0, owner) }}'
        elif (t := inner(ty, 'Arc')) is not None:
            self.export(f, arg, ('*const c_void', 'const void *'), f'Arc::as_ptr({ptr}).cast()')
            value = f'{self.reader(t)}({f}(pointer)!, owner)'
        elif (t := inner(ty, 'Vec')) is not None or ty.startswith('['):
            if t is None:
                t = ty[1:ty.index(';')].strip()
            self.export(f, arg, ('Slice', 'DHSlice'), f'Slice::new({ptr})')
            value = f'RustArray({f}(pointer), owner: owner, read: {self.reader(t)})'
        elif ty.startswith(('BTreeMap<', 'HashMap<', 'BTreeSet<')):
            return self.collection_reader(ty, name)
        elif ty in self.models:
            value = f'{ty}.read(pointer, owner)' if self.models[ty][1] == 'enum' else f'{ty}(pointer: pointer, owner: owner)'
        else:
            raise ValueError(f'No projection for {ty}')
        self.swift.append(f'func {name}(_ pointer: UnsafeRawPointer, _ owner: RustOwner) -> {self.swift_type(ty)} {{ {value} }}')
        return name

    def collection_reader(self, ty, name):
        f = 'dh_each_' + key(ty)
        is_set = ty.startswith('BTreeSet<')
        k, v = (inner(ty, 'BTreeSet'), None) if is_set else split(ty[ty.index('<')+1:-1])
        if v and k in PRIMITIVES and v in PRIMITIVES:
            get = 'dh_get_' + key(ty)
            equal = 'dh_equal_' + key(ty)
            self.export(get, [('pointer', '*const c_void', 'const void *'), ('key', k, PRIMITIVES[k][0])],
                        ('*const c_void', 'const void *'),
                        f'(&*pointer.cast::<{ty}>()).get(&key).map_or(std::ptr::null(), |v| (v as *const {v}).cast())')
            self.export(equal, [('lhs', '*const c_void', 'const void *'), ('rhs', '*const c_void', 'const void *')],
                        ('bool', 'bool'), f'(*lhs.cast::<{ty}>()) == (*rhs.cast::<{ty}>())')
            arg = 'UInt(key)' if k == 'usize' else 'key'
            self.swift.append(f'''func {name}(_ pointer: UnsafeRawPointer, _ owner: RustOwner) -> {self.swift_type(ty)} {{
    RustMap(pointer: pointer, owner: owner, get: {{ pointer, key in
        {get}(pointer, {arg}).map {{ {load_primitive(v, '$0')} }}
    }}, equal: {{ {equal}($0, $1) }})
}}''')
            return name
        callback = 'unsafe extern "C" fn(*mut c_void, *const c_void' + (', *const c_void' if v else '') + ')'
        item = '(key, value)' if v else 'key'
        visit = f'visit(context, (key as *const {k}).cast()' + (f', (value as *const {v}).cast()' if v else '') + ')'
        self.rust.append(f'#[unsafe(no_mangle)]\npub unsafe extern "C" fn {f}(pointer: *const c_void, context: *mut c_void, visit: {callback}) {{\nunsafe {{ for {item} in &*pointer.cast::<{ty}>() {{ {visit}; }} }}\n}}')
        self.header.append(f'void {f}(const void *pointer, void *context, void (*visit)(void *, const void *' + (', const void *' if v else '') + '));')
        sw = self.swift_type(ty)
        self.reader(k)
        if v:
            self.reader(v)

        def read(t, p):
            if t == 'String':
                return f'readString(dh_read_String({p}!))'
            assert t in PRIMITIVES
            return load_primitive(t, f'{p}!')

        value = f'result.pointee[{read(k, "key")}] = {read(v, "value")}' if v else f'result.pointee.append({read(k, "key")})'
        self.swift.append(f'''func {name}(_ pointer: UnsafeRawPointer, _ owner: RustOwner) -> {sw} {{
    var result: {sw} = {'[:]' if v else '[]'}
    withUnsafeMutablePointer(to: &result) {{ context in
        {f}(pointer, context) {{ context, key{', value' if v else ''} in
            let result = context!.assumingMemoryBound(to: {sw}.self)
            {value}
        }}
    }}
    return result
}}''')
        return name

    def models_code(self):
        for name, (module, kind, body) in sorted(self.models.items()):
            if name == 'AnalysisOptions':
                self.swift.append('public struct AnalysisOptions: Sendable, Equatable { public var nativeMemoryRoots: Bool; public init(nativeMemoryRoots: Bool) { self.nativeMemoryRoots = nativeMemoryRoots } }')
                continue
            if kind == 'enum':
                self.enum_code(name, body)
                continue
            fields = [(f.split(':', 1)[0].strip().removeprefix('pub '), clean(f.split(':', 1)[1])) for f in split(body)]
            pod = all(ty in PRIMITIVES for _, ty in fields)
            if pod:
                crate = 'heap-core' if module.startswith('heap_core') else 'heap-bridge'
                source = (ROOT / f'crates/{crate}/src/{module.split("::")[-1]}.rs').read_text()
                assert f'#[repr(C)]\npub struct {name} {{' in source, f'{name} needs repr(C)'
                members = ' '.join(PRIMITIVES[t][0] + ' ' + f + ';' for f, t in fields)
                self.header.append(f'typedef struct {{ {members} }} DH{name};')
            props = []
            for field, ty in fields:
                f = f'dh_{name}_{field.removeprefix("r#")}'
                args = [('pointer', '*const c_void', 'const void *')]
                if pod:
                    read = f'pointer.assumingMemoryBound(to: DH{name}.self).pointee.{field}'
                    if ty == 'usize':
                        read = f'Int({read})'
                elif ty in PRIMITIVES:
                    self.export(f, args, (ty, PRIMITIVES[ty][0]), f'(*pointer.cast::<{name}>()).{field}')
                    read = f'{f}(pointer)'
                    if ty == 'usize':
                        read = f'Int({read})'
                else:
                    self.export(f, args, ('*const c_void', 'const void *'), f'(&(*pointer.cast::<{name}>()).{field} as *const {ty}).cast()')
                    read = f'{self.reader(ty)}({f}(pointer)!, owner)'
                read = re.sub(r'\b(pointer|owner)\b', r'_\1', read)
                props.append(f'    public var {swift_name(field)}: {self.swift_type(ty)} {{ withExtendedLifetime(_owner) {{ {read} }} }}')
            eq = ' &&\n            '.join(f'lhs.{swift_name(f)} == rhs.{swift_name(f)}' for f, t in fields) or 'true'
            self.swift.append(f'''public struct {name}: @unchecked Sendable, Equatable {{
    let _pointer: UnsafeRawPointer
    let _owner: RustOwner
    init(pointer: UnsafeRawPointer, owner: RustOwner) {{ _pointer = pointer; _owner = owner }}
{chr(10).join(props)}
    public static func == (lhs: Self, rhs: Self) -> Bool {{
        if lhs._pointer == rhs._pointer {{ return true }}
        return {eq}
    }}
}}''')

    def enum_code(self, name, body):
        cases, switch, patterns = [], [], []
        for index, case in enumerate(split(body)):
            variant = re.match(r'\w+', case)[0]
            if '(' in case:
                fields = [(f'v{i}', clean(t)) for i, t in enumerate(split(case[case.index('(')+1:-1]))]
                pattern = f'{name}::{variant}(' + ', '.join(f for f, t in fields) + ')'
                labels = False
            elif '{' in case:
                fields = [(f.split(':', 1)[0].strip(), clean(f.split(':', 1)[1])) for f in split(case[case.index('{')+1:-1])]
                pattern = f'{name}::{variant} {{ ' + ', '.join(f for f, t in fields) + ' }'
                labels = True
            else:
                fields, pattern, labels = [], f'{name}::{variant}', False
            patterns.append(pattern)
            args = []
            for field, ty in fields:
                f = f'dh_{name}_{variant}_{field}'
                self.export(f, [('pointer', '*const c_void', 'const void *')], ('*const c_void', 'const void *'), f'if let {pattern} = &*pointer.cast::<{name}>() {{ ({field} as *const {ty}).cast() }} else {{ std::ptr::null() }}')
                args.append((swift_name(field) + ': ' if labels else '') + f'{self.reader(ty)}({f}(pointer)!, owner)')
            declaration = ', '.join((swift_name(f) + ': ' if labels else '') + self.swift_type(t) for f, t in fields)
            cases.append('    case ' + swift_name(variant) + ('(' + declaration + ')' if fields else ''))
            switch.append(f'        case {index}: return .{swift_name(variant)}' + ('(' + ', '.join(args) + ')' if args else ''))
        patterns = [re.sub(r'\(.*\)', '(..)', p) if '(' in p else re.sub(r'\{.*\}', '{ .. }', p) for p in patterns]
        f = 'dh_tag_' + name
        arms = ', '.join(f'{p} => {i}' for i, p in enumerate(patterns))
        self.export(f, [('pointer', '*const c_void', 'const void *')], ('u32', 'uint32_t'), f'match &*pointer.cast::<{name}>() {{ {arms} }}')
        self.swift.append(f'''public enum {name}: Sendable, Hashable {{
{chr(10).join(cases)}
    static func read(_ pointer: UnsafeRawPointer, _ owner: RustOwner) -> Self {{
        switch {f}(pointer) {{
{chr(10).join(switch)}
        default: preconditionFailure("Invalid Rust {name}")
        }}
    }}
}}''')

    def methods(self):
        found = []
        for module in ['snapshot', 'graphs', 'objects', 'system']:
            source = (ROOT / f'crates/heap-bridge/src/{module}.rs').read_text()
            if module == 'system':
                blocks = [(None, source)]
            else:
                blocks = [(m[1], source[m.end():source.index('\n}', m.end())]) for m in re.finditer(r'^impl (\w+) \{', source, re.M) if m[1] in OBJECTS]
            for obj, body in blocks:
                pattern = r'    pub fn (\w+)\(' if obj else r'^pub fn (\w+)\('
                for match in re.finditer(pattern, body, re.M):
                    end = body.index(') ->', match.end())
                    args = split(body[match.end():end])
                    result = clean(body[end+5:body.index('{', end)].strip())
                    found.append((module, obj, match[1], args, result))
        return found

    def functions_code(self):
        methods = {o: [] for o in OBJECTS}
        for module, obj, name, params, result in self.methods():
            rsargs, swargs, callargs, swift_callargs, wrappers, lifetimes = [], [], [], [], [], []
            if obj and params and params[0] == '&self':
                params = params[1:]
                rsargs.append(('pointer', '*const c_void', 'const void *'))
                swift_callargs.append('pointer')
                lifetimes.append('owner')
                receiver = f'(&*pointer.cast::<{obj}>()).'
            else:
                receiver = f'{obj}::' if obj else f'crate::{module}::'
            for param in params:
                p, t = param.split(':', 1)
                p, t = p.strip(), clean(t)
                s = swift_name(p)
                swift_arg = s
                if t in PRIMITIVES:
                    rsargs.append((p, t, PRIMITIVES[t][0]))
                    swargs.append((s, self.swift_type(t)))
                    callargs.append(p)
                    if t == 'usize':
                        swift_arg = f'UInt({s})'
                elif t in ('String', '&str'):
                    rsargs.append((p, 'Slice', 'DHSlice'))
                    swargs.append((s, 'String'))
                    callargs.append(f'ffi::string({p})' + ('.to_owned()' if t == 'String' else ''))
                    wrappers.append(f'withRustString({s}) {{ {s} in')
                elif t == 'Option<String>':
                    rsargs.append((p, 'ffi::OptionalString', 'DHOptionalString'))
                    swargs.append((s, 'String?'))
                    callargs.append(f'{p}.present.then(|| ffi::string({p}.value).to_owned())')
                    wrappers.append(f'withOptionalRustString({s}) {{ {s} in')
                elif t in ('Vec<String>', '&[String]'):
                    rsargs.append((p, 'Slice', 'DHSlice'))
                    swargs.append((s, '[String]'))
                    expr = f'ffi::slice::<Slice>({p}).iter().map(|s| ffi::string(Slice {{ data:s.data, len:s.len, stride:s.stride }}).to_owned()).collect::<Vec<_>>()'
                    callargs.append(('&' if t.startswith('&') else '') + expr)
                    wrappers.append(f'withRustStrings({s}) {{ {s} in')
                elif t.startswith('&[') and t[2:-1] in PRIMITIVES:
                    rsargs.append((p, 'Slice', 'DHSlice'))
                    swargs.append((s, self.swift_type(t)))
                    callargs.append(f'ffi::slice::<{t[2:-1]}>({p})')
                    swift_arg = f'{s}.storage'
                    lifetimes.append(s)
                elif 'dyn Progress' in t:
                    optional = t.startswith('Option')
                    rsargs.append((p, 'ffi::Progress', 'DHProgress'))
                    swargs.append((s, '(any Progress)' + ('?' if optional else '')))
                    callargs.append(f'if {p}.context.is_null() {{ None }} else {{ Some(Box::new({p}) as Box<dyn Progress>) }}' if optional else f'Box::new({p})')
                    swift_arg = f'{s}.map(transferProgress) ?? DHProgress()' if optional else f'transferProgress({s})'
                elif t == 'AnalysisOptions':
                    rsargs.append((p, 'bool', 'bool'))
                    swargs.append((s, 'AnalysisOptions'))
                    callargs.append(f'AnalysisOptions {{ native_memory_roots: {p} }}')
                    swift_arg = f'{s}.nativeMemoryRoots'
                elif t == 'Vec<&TimerInfo>':
                    rsargs.append((p, 'Slice', 'DHSlice'))
                    swargs.append((s, '[TimerInfo]'))
                    callargs.append(f'ffi::slice::<*const TimerInfo>({p}).iter().map(|p| &**p).collect()')
                    wrappers.append(f'withRustPointers({s}.map(\\._pointer)) {{ {s} in')
                    lifetimes.append(s)
                else:
                    base = (inner(t, 'Arc') or t.removeprefix('&')).removeprefix('crate::snapshot::')
                    rsargs.append((p, '*const c_void', 'const void *'))
                    swargs.append((s, base))
                    lifetimes.append(s)
                    swift_arg = f'{s}.pointer' if base in OBJECTS else f'{s}._pointer'
                    if t.startswith('&'):
                        callargs.append(f'&*{p}.cast::<{base}>()')
                    elif t.startswith('Arc<'):
                        callargs.append(f'{{ Arc::increment_strong_count({p}.cast::<{base}>()); Arc::from_raw({p}.cast::<{base}>()) }}')
                    else:
                        callargs.append(f'(*{p}.cast::<{base}>()).clone()')
                swift_callargs.append(swift_arg)
            throws = inner(result, 'Result')
            ret = (throws or result).replace('Self', obj or '')
            owned = inner(ret, 'Arc')
            fn = f'dh_{obj + "_" if obj else ""}{name}'
            call = f'{receiver}{name}(' + ', '.join(callargs) + ')' + ('?' if throws else '')
            if ret.startswith('Option<&'):
                assert not throws and obj
                ty = ret[len('Option<&'):-1]
                self.export(fn, rsargs, ('*const c_void', 'const void *'),
                            f'{call}.map_or(std::ptr::null(), |value| (value as *const {ty}).cast())')
                swbody = f'return CALL.map {{ {self.reader(ty)}($0, owner) }}'
            elif ret.startswith('&'):
                assert not throws
                if ret.startswith('&['):
                    self.export(fn, rsargs, ('Slice', 'DHSlice'), f'Slice::new({call})')
                    read = f'RustArray(value, owner: owner, read: {self.reader(ret[2:-1])})'
                else:
                    self.export(fn, rsargs, ('*const c_void', 'const void *'), f'({call} as *const {ret[1:]}).cast()')
                    read = f'{self.reader(ret[1:])}(value!, owner)'
                swbody = 'let value = CALL\nreturn ' + read
            elif ret in PRIMITIVES and not throws:
                self.export(fn, rsargs, (ret, PRIMITIVES[ret][0]), call)
                swbody = 'return Int(CALL)' if ret == 'usize' else 'return CALL'
            else:
                self.export(fn, rsargs, ('Outcome', 'DHOutcome'), f'ffi::call(|| Ok(Owned::{"arc" if owned else "new"}({call})))')
                reader = self.reader(owned or ret)
                lift = f'{reader}(result.pointer, result)' if not reader.startswith('{') else f'{owned or ret}(owner: result)'
                swbody = 'let result = ' + ('try take' if throws else 'checked') + '(CALL)\nreturn withExtendedLifetime(result) { ' + lift + ' }'
            swbody = swbody.replace('CALL', fn + '(' + ', '.join(swift_callargs) + ')')
            if lifetimes:
                wrappers.insert(0, 'withExtendedLifetime((' + ', '.join(lifetimes) + ')) {')
            for w in reversed(wrappers):
                swbody = ('return try ' if throws else 'return ') + w + '\n' + textwrap.indent(swbody, '    ') + '\n}'
            signature = f'public {"static " if name == "open" and obj else ""}func {swift_name(name)}(' + ', '.join(f'{p}: {t}' for p, t in swargs) + ')'
            signature += (' throws' if throws else '') + ' -> ' + self.swift_type(ret)
            code = signature + ' {\n' + '\n'.join('    ' + line for line in swbody.splitlines()) + '\n}'
            if obj:
                methods[obj].append(code)
            else:
                self.swift.append(code)
        for obj, contents in methods.items():
            self.swift.append(f'''public final class {obj}: @unchecked Sendable {{
    let owner: RustOwner
    var pointer: UnsafeRawPointer {{ owner.pointer }}
    init(owner: RustOwner) {{ self.owner = owner }}
{textwrap.indent(chr(10).join(contents), '    ')}
}}''')

    def write(self):
        aliases = ['// Generated by scripts/generate-bridge-models.py.']
        for name, (module, _, _) in sorted(self.models.items()):
            if module.startswith('heap_core'):
                aliases.append(f'pub use {module}::{name};')
        (ROOT / 'crates/heap-bridge/src/models.rs').write_text('\n'.join(aliases) + '\n')
        self.reader('String')
        self.models_code()
        self.functions_code()
        rust_path = ROOT / 'crates/heap-bridge/src/generated.rs'
        rust_path.write_text('\n\n'.join(self.rust) + '\n')
        (ROOT / 'Sources/RustHeapCore/Generated.swift').write_text('\n\n'.join(self.swift) + '\n')
        header = ROOT / 'Sources/RustHeapCoreFFI'
        header.mkdir(exist_ok=True)
        (header / 'RustHeapCoreFFI.h').write_text('\n'.join(self.header) + '\n')
        (header / 'module.modulemap').write_text('module RustHeapCoreFFI { header "RustHeapCoreFFI.h" export * }\n')
        subprocess.run(['rustfmt', '--edition', '2024', str(rust_path), str(ROOT / 'crates/heap-bridge/src/models.rs')], check=True)


